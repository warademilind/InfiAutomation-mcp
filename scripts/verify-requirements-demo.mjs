import assert from 'node:assert/strict';
import { mkdir, mkdtemp, writeFile } from 'node:fs/promises';
import { resolve, join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { chromium } from 'playwright';
import { initDemo } from '../dist/demo.js';
import { Workspace } from '../dist/workspace.js';
import { runSuite } from '../dist/runner.js';
await mkdir('.infiautomation',{recursive:true});
const workspace=new Workspace(await mkdtemp(resolve('.infiautomation/demo-ui-')));
await initDemo(workspace);
const suite=JSON.parse(await workspace.read('infi-demo/suite.json'));
const out=await runSuite(suite,workspace);
assert.deepEqual(out.result.summary,{total:3,passed:3,failed:0,healed:0,skipped:0});
assert.equal(out.result.traceability.unmapped,0);
const browser=await chromium.launch();
try{
 const page=await browser.newPage({viewport:{width:1512,height:1000}}),errors=[];
 page.on('pageerror',error=>errors.push(String(error)));
 await page.goto(pathToFileURL(join(out.directory,'traceability.html')).href);
 await page.getByRole('heading',{name:'Project form requirement-based plan'}).waitFor();
 assert.equal(await page.locator('tbody tr:visible').count(),3);
 assert.equal(await page.getByText('Open business questions',{exact:true}).isVisible(),true);
 await mkdir('integration/output',{recursive:true});
 await page.screenshot({path:'integration/output/traceability-desktop.png',fullPage:true});
 await page.getByRole('searchbox').fill('REQ-EXPORT');assert.equal(await page.locator('tbody tr:visible').count(),1);
 await page.getByRole('searchbox').fill('');
 await page.getByRole('combobox').selectOption('unmapped');assert.equal(await page.locator('tbody tr:visible').count(),0);
 await page.getByRole('combobox').selectOption('all');
 await page.getByRole('link',{name:'save-project',exact:true}).click();
 await page.getByRole('dialog').waitFor();assert.equal(await page.getByRole('heading',{name:'Save a named project',exact:true}).isVisible(),true);
 await page.keyboard.press('Escape');
 await page.getByRole('searchbox').fill('REQ-SAVE-001');assert.equal(await page.locator('#rows tr').count(),1);
 await page.goto(pathToFileURL(join(out.directory,'index.html')).href);
 await page.getByRole('link',{name:'Requirement coverage and test mappings'}).click();
 await page.setViewportSize({width:390,height:844});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth),false);
 await page.screenshot({path:'integration/output/traceability-mobile.png',fullPage:true});
 assert.deepEqual(errors,[]);
 await writeFile('integration/output/requirements-report-path.txt',out.directory);
 console.log(JSON.stringify({directory:out.directory,cases:3,requirements:3,verified:['bundled demo','relative workspace URLs','coverage metrics','open questions','search and status filters','case drilldown','requirement search in detailed report','summary coverage link','mobile layout']},null,2));
}finally{await browser.close()}
